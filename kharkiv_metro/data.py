"""Статичні дані Харківського метро: лінії, пересадки, час руху.

Усе зібрано в одному місці — додавання станції чи зміна часу руху
вимагає правки тільки тут.
"""

from dataclasses import dataclass
from typing import Dict, List, Tuple


@dataclass(frozen=True)
class Line:
    """Лінія метро.

    Attributes:
        code: коротка назва (M1, M2, M3).
        name: повна назва лінії.
        color: hex-колір для рендеру.
        stations: упорядкований кортеж назв станцій від одного кінця до іншого.
    """

    code: str
    name: str
    color: str
    stations: Tuple[str, ...]


@dataclass(frozen=True)
class Transfer:
    """Пересадка між двома станціями різних ліній."""

    stations: Tuple[str, str]


